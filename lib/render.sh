#!/usr/bin/env bash
# shellcheck disable=SC2034  # globals are shared across the sourced modules
# render.sh — turn the model into unit-file text.
# Output: UNITS[filename]=content, UNIT_ORDER=(filenames…)

declare -gA UNITS=()
declare -ga UNIT_ORDER=()
BUF=""

_l() { BUF+="$1"$'\n'; }
_kv() { if [[ -n ${2-} ]]; then _l "$1=$2"; fi; }
_sec() {
  [[ -z $BUF || $BUF == *$'\n\n' ]] || _l ""
  _l "[$1]"
}
_header() {
  _l "# Generated by ssg $(ssg_version) — $SSG_REPO_URL"
  _l "# Review before use; regenerate rather than hand-editing where possible."
}
# user-supplied --set Section.Key=Value lines for one section
_extras() {
  local sec=$1 item
  while IFS= read -r item; do
    [[ -z $item ]] && continue
    if [[ ${item%%.*} == "$sec" ]]; then _l "${item#*.}"; fi
  done <<< "${U[set]:-}"
}

render_all() {
  UNITS=()
  UNIT_ORDER=()
  local n=${U[name]} f
  if [[ ${U[has_timer]} == yes ]]; then
    render_timer
    UNITS[$n.timer]=$BUF
    UNIT_ORDER+=("$n.timer")
  fi
  if [[ ${U[has_socket]} == yes ]]; then
    render_socket
    UNITS[$n.socket]=$BUF
    UNIT_ORDER+=("$n.socket")
  fi
  if [[ ${U[has_path]} == yes ]]; then
    render_path
    UNITS[$n.path]=$BUF
    UNIT_ORDER+=("$n.path")
  fi
  render_service
  UNITS[$n.service]=$BUF
  UNIT_ORDER+=("$n.service")
  for f in "${UNIT_ORDER[@]}"; do dbg "rendered $f ($(wc -l <<< "${UNITS[$f]}") lines)"; done
}

_triggered() { [[ ${U[has_timer]} == yes || ${U[has_socket]} == yes || ${U[has_path]} == yes ]]; }

render_service() {
  BUF=""
  local scope=${U[scope]} ver item line
  ver=$(sd_version)
  _header
  _sec Unit
  _kv Description "$(esc_pct "${U[desc]}")"
  while IFS= read -r item; do [[ -n $item ]] && _l "Documentation=$item"; done <<< "${U[doc]:-}"
  local k
  for k in after wants requires; do
    if d_has "$k"; then
      _l "${k^}=$(d_list "$k" | paste -sd' ' -)"
    fi
  done
  [[ -n ${U[on_failure]:-} ]] && _kv OnFailure "${U[on_failure]}"
  _kv StartLimitIntervalSec "${U[start_limit_interval]:-}"
  _kv StartLimitBurst "${U[start_limit_burst]:-}"
  _extras Unit

  _sec Service
  _kv Type "${U[type]}"
  if [[ $scope == system ]]; then
    if [[ ${U[dynamic_user]:-no} == yes ]]; then
      _l "DynamicUser=yes"
    else
      _kv User "${U[user]:-}"
      _kv Group "${U[group]:-}"
    fi
  fi
  _kv WorkingDirectory "${U[workdir]:-}"
  while IFS= read -r item; do
    [[ -n $item ]] && _l "Environment=\"$(esc_env "$item")\""
  done <<< "${U[env]:-}"
  _kv EnvironmentFile "${U[env_file]:-}"
  while IFS= read -r item; do
    [[ -n $item ]] && _l "ExecStartPre=$(esc_pct "$(resolve_exec "$item")")"
  done <<< "${U[pre]:-}"
  _l "ExecStart=$(esc_pct "$(resolve_exec "${U[exec]}")")"
  while IFS= read -r item; do
    [[ -n $item ]] && _l "ExecStartPost=$(esc_pct "$(resolve_exec "$item")")"
  done <<< "${U[post]:-}"
  [[ -n ${U[reload]:-} ]] && _l "ExecReload=$(esc_pct "$(resolve_exec "${U[reload]}")")"
  [[ -n ${U[stop]:-} ]] && _l "ExecStop=$(esc_pct "$(resolve_exec "${U[stop]}")")"
  if [[ ${U[restart]} != no ]]; then
    _l "Restart=${U[restart]}"
    _kv RestartSec "${U[restart_sec]:-}"
  fi
  _kv TimeoutStopSec "${U[stop_timeout]:-}"
  if [[ ${U[type]} == oneshot && ${U[remain]:-no} == yes ]]; then _l "RemainAfterExit=yes"; fi
  _kv SyslogIdentifier "${U[syslog_id]:-}"
  if [[ -n ${U[logfile]:-} ]]; then
    if ((ver >= 240)); then
      _l "StandardOutput=append:${U[logfile]}"
      _l "StandardError=inherit"
    else
      warn "Log files need systemd >= 240 (target is $ver); logging to the journal instead."
    fi
  fi

  # state / cache / logs / runtime / config directories (auto-created, auto-writable)
  _kv StateDirectory "${U[state_dir]:-}"
  _kv CacheDirectory "${U[cache_dir]:-}"
  _kv LogsDirectory "${U[logs_dir]:-}"
  _kv RuntimeDirectory "${U[runtime_dir]:-}"
  _kv ConfigurationDirectory "${U[config_dir]:-}"

  # resources
  _kv CPUQuota "${U[cpu_quota]:-}"
  _kv MemoryMax "${U[mem_max]:-}"
  _kv TasksMax "${U[tasks_max]:-}"
  _kv LimitNOFILE "${U[nofile]:-}"
  _kv Nice "${U[nice]:-}"
  _kv UMask "${U[umask]:-}"

  # sandbox
  harden_lines "${U[harden]}" "$scope"
  if ((${#HARDEN_LINES[@]})); then
    _l "# --- sandbox: ${U[harden]} ---"
    for line in "${HARDEN_LINES[@]}"; do _l "$line"; done
  fi
  local -a rw=()
  if [[ ${U[harden]} == strict && -n ${U[logfile]:-} ]]; then rw+=("-${U[logfile]%/*}"); fi
  while IFS= read -r item; do [[ -n $item ]] && rw+=("$item"); done <<< "${U[rw_path]:-}"
  if ((${#rw[@]})); then _l "ReadWritePaths=${rw[*]}"; fi
  if d_has ro_path; then _l "ReadOnlyPaths=$(d_list ro_path | paste -sd' ' -)"; fi
  _extras Service

  if ! _triggered; then
    _sec Install
    _l "WantedBy=${U[wantedby]}"
    _extras Install
  elif [[ -n ${U[set]:-} && ${U[set]} == *Install.* ]]; then
    _sec Install
    _extras Install
  fi
}

_trigger_desc() { printf '%s' "$(esc_pct "${U[desc]}")"; }

render_timer() {
  BUF=""
  _header
  _sec Unit
  _l "Description=Timer for $(_trigger_desc)"
  _sec Timer
  _kv OnCalendar "${U[on_calendar]:-}"
  if [[ -n ${U[every]:-} ]]; then
    _l "OnBootSec=${U[every]}"
    _l "OnUnitActiveSec=${U[every]}"
  fi
  [[ ${U[persistent]:-no} == yes && -n ${U[on_calendar]:-} ]] && _l "Persistent=true"
  _kv RandomizedDelaySec "${U[random_delay]:-}"
  _kv AccuracySec "${U[accuracy]:-}"
  _extras Timer
  _sec Install
  _l "WantedBy=timers.target"
}

render_socket() {
  BUF=""
  local item
  _header
  _sec Unit
  _l "Description=Socket for $(_trigger_desc)"
  _sec Socket
  while IFS= read -r item; do
    [[ -z $item ]] && continue
    if [[ $item == udp:* ]]; then _l "ListenDatagram=${item#udp:}"; else _l "ListenStream=$item"; fi
  done <<< "${U[listen]:-}"
  _extras Socket
  _sec Install
  _l "WantedBy=sockets.target"
}

render_path() {
  BUF=""
  local item k
  _header
  _sec Unit
  _l "Description=Path trigger for $(_trigger_desc)"
  _sec Path
  for k in watch:PathChanged watch_modified:PathModified watch_exists:PathExists watch_dir:DirectoryNotEmpty; do
    while IFS= read -r item; do
      [[ -n $item ]] && _l "${k#*:}=$item"
    done <<< "${U[${k%%:*}]:-}"
  done
  _extras Path
  _sec Install
  _l "WantedBy=paths.target"
}
